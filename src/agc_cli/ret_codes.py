def ret_failure(code: Any, msg: Any) -> tuple[str, str]:
    """Return the CLI message and detail for a non-zero Huawei ret."""

    text = msg.strip() if isinstance(msg, str) else ""
    usable = bool(text) and text.lower() != "success"
    description = RET_MESSAGES.get(code) if isinstance(code, int) and not isinstance(code, bool) else None
    if description is not None:
        message = f"{description}：{text}" if code in _FOLLOW_MSG and usable else description
    elif usable:
        message = text
    else:
        message = f"华为接口返回业务错误（{code}）"
    if text.lower() == "unknown error":
        message = f"{message}。可通过在线工单联系华为"
    return message, f"{code}: {text}"
