var followMessage = map[int]struct{}{204144641: {}, 204144642: {}, 204144758: {}}

// Failure returns the CLI message and detail for a non-zero Huawei ret.
func Failure(code any, msg any) (string, string) {
	text := ""
	if value, ok := msg.(string); ok {
		text = strings.TrimSpace(value)
	}
	usable := text != "" && strings.ToLower(text) != "success"
	number, validCode := integer(code)
	description, known := messages[number]
	var message string
	if validCode && known {
		if _, follow := followMessage[number]; follow && usable {
			message = description + "：" + text
		} else {
			message = description
		}
	} else if usable {
		message = text
	} else {
		message = fmt.Sprintf("华为接口返回业务错误（%s）", display(code))
	}
	if strings.ToLower(text) == "unknown error" {
		message += "。可通过在线工单联系华为"
	}
	return message, fmt.Sprintf("%s: %s", display(code), text)
}

func integer(value any) (int, bool) {
	switch typed := value.(type) {
	case int:
		return typed, true
	case int64:
		return int(typed), true
	case json.Number:
		parsed, err := typed.Int64()
		return int(parsed), err == nil
	case float64:
		if typed == float64(int64(typed)) {
			return int(typed), true
		}
	}
	return 0, false
}

func display(value any) string {
	switch typed := value.(type) {
	case nil:
		return "None"
	case json.Number:
		return typed.String()
	case float64:
		return fmt.Sprintf("%v", typed)
	default:
		return fmt.Sprintf("%v", typed)
	}
}
